import { getTranslations, type Translations } from "@/lib/core/i18n";

import { en } from "./en";

export type Language = "en" | "nl" | "de" | "fr";

export function picnicStrings(language: Language): Translations {
  if (language === "en") return en;
  return getTranslations(language === "nl" ? "NL" : language === "de" ? "DE" : "FR");
}

