// Write src/server/routes.generated.ts: one entry per picnic-web API route.
//
//   node scripts/routes.mjs          write the file
//   node scripts/routes.mjs --check  fail when the file is out of date
//
// Every route file under vendor/picnic-web/src/app/api is served, except the
// ones listed in SKIPPED. tests/routes.test.ts checks the table against the
// folder, so a route that picnic-web adds is never silently left out.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const API = "vendor/picnic-web/src/app/api";
const OUT = "src/server/routes.generated.ts";

/** Routes Picnic Desk does not serve, and why. */
export const SKIPPED = {
  "user/referral": "friend referral: not wanted",
  "user/family": "family accounts: not wanted",
  wallet: "wallet and payment methods: not wanted",
  "wallet/balance": "wallet and payment methods: not wanted",
  "wallet/transactions/[transactionId]": "wallet and payment methods: not wanted",
  image: "replaced by /api/desk/image, which tries several picture variants",
};

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : name === "route.ts" ? [path] : [];
  });
}

export function routeFiles() {
  return walk(API)
    .map((file) => relative(API, file).split(sep).slice(0, -1).join("/"))
    .sort();
}

function methodsOf(route) {
  const source = readFileSync(join(API, route, "route.ts"), "utf8");
  return [...source.matchAll(/export async function (GET|POST|PUT|DELETE|PATCH)\b/g)].map((m) => m[1]);
}

function render() {
  const served = routeFiles().filter((route) => !(route in SKIPPED));
  const imports = served.map((route, i) => `import * as r${i} from "@/app/api/${route}/route";`);
  const entries = served.map((route, i) => {
    const methods = methodsOf(route);
    return `  { path: ${JSON.stringify(route)}, methods: ${JSON.stringify(methods)}, module: r${i} as RouteModule },`;
  });
  return [
    "// Generated by scripts/routes.mjs from vendor/picnic-web/src/app/api. Do not edit.",
    'import type { RouteModule } from "./router";',
    ...imports,
    "",
    "export const VENDORED_ROUTES = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split(sep).pop())) {
  const text = render();
  if (process.argv.includes("--check")) {
    if (readFileSync(OUT, "utf8") !== text) {
      console.error(`${OUT} is out of date: run node scripts/routes.mjs`);
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
